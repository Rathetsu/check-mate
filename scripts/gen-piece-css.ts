// Writes apps/web/src/styles/pieces.css from the piece sets copied by
// fetch-lila-assets.sh: one `.pieces-<set>` block per set. chessground draws
// `<piece>` elements; the promotion picker and editor palette use `.cg-piece`.
//   node scripts/gen-piece-css.ts
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const PIECES = join(ROOT, 'apps/web/public/assets/piece');
const OUT = join(ROOT, 'apps/web/src/styles/pieces.css');
const ROLES = { pawn: 'P', knight: 'N', bishop: 'B', rook: 'R', queen: 'Q', king: 'K' } as const;

const blocks = readdirSync(PIECES)
  .sort()
  .map((set) => {
    const rules = (['white', 'black'] as const).flatMap((color) =>
      Object.entries(ROLES).map(([role, letter]) => {
        // `mono` draws both colors with one image (lila's blindfold-style set).
        const file = existsSync(join(PIECES, set, `${color[0]}${letter}.svg`)) ? `${color[0]}${letter}` : letter;
        return `  :is(piece, .cg-piece).${color}.${role} { background-image: url('/assets/piece/${set}/${file}.svg'); }`;
      }),
    );
    return `.pieces-${set} {\n${rules.join('\n')}\n}`;
  });

writeFileSync(OUT, `/* Generated by scripts/gen-piece-css.ts. Do not edit. */\n${blocks.join('\n')}\n`);
console.info(`Wrote ${blocks.length} piece sets to ${OUT}`);
